import logging
import threading
from contextlib import asynccontextmanager
from pathlib import Path

from apscheduler.schedulers.background import BackgroundScheduler
from fastapi import BackgroundTasks, FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

from . import agent, db, indexer, reviewer
from .config import settings
from .llm import get_llm, llm_text

logging.basicConfig(level=logging.INFO)
log = logging.getLogger("main")

# Directory for static UI assets
STATIC = Path(__file__).resolve().parent.parent / "static"
_sync_lock = threading.Lock()
_sync_state = {"running": False, "last": None}


def run_sync(force: bool = False) -> None:
    """Runs the repository synchronization process in the background. Locks to prevent concurrent syncs."""
    if not _sync_lock.acquire(blocking=False):
        return  # a sync is already running
    _sync_state["running"] = True
    try:
        # Sync repos from GitHub, index code chunks, update summaries
        _sync_state["last"] = indexer.sync_all(force=force)
    except Exception as e:  # noqa: BLE001
        log.exception("sync failed")
        _sync_state["last"] = [{"error": str(e)}]
    finally:
        _sync_state["running"] = False
        _sync_lock.release()


@asynccontextmanager
async def lifespan(_: FastAPI):
    """Lifecycle manager for FastAPI to initialize DB and start the sync scheduler."""
    db.init_db()
    sched = BackgroundScheduler()
    # Schedule periodic sync based on settings
    sched.add_job(run_sync, "interval", hours=settings.sync_interval_hours, id="sync")
    sched.start()
    yield
    sched.shutdown(wait=False)


app = FastAPI(title="Repo Agent", lifespan=lifespan)

# Request Models
class ChatIn(BaseModel):
    thread_id: str = "default"
    message: str


class ApproveIn(BaseModel):
    thread_id: str = "default"
    approved: bool


class StatusIn(BaseModel):
    status: str  # open | accepted | dismissed | done


# API Endpoints

@app.post("/api/chat")
def chat(body: ChatIn):
    """Interact with the LangGraph agent."""
    try:
        return agent.chat(body.thread_id, body.message)
    except RuntimeError as e:
        raise HTTPException(400, str(e))


@app.post("/api/approve")
def approve(body: ApproveIn):
    """Approve or reject a pending tool execution (human-in-the-loop)."""
    return agent.resume(body.thread_id, body.approved)


@app.post("/api/sync")
def sync(bg: BackgroundTasks, force: bool = False):
    """Trigger a manual background sync."""
    if _sync_state["running"]:
        return {"started": False, "detail": "sync already running"}
    bg.add_task(run_sync, force)
    return {"started": True}


@app.get("/api/sync/status")
def sync_status():
    """Get the current sync status."""
    return _sync_state


@app.get("/api/repos")
def repos():
    """List all tracked repositories."""
    return db.list_repos()


@app.get("/api/suggestions")
def suggestions(repo: str | None = None, status: str | None = "open"):
    """Get automated improvement suggestions generated by the reviewer."""
    return db.list_suggestions(repo=repo, status=status)


@app.post("/api/suggestions/{sid}")
def update_suggestion(sid: int, body: StatusIn):
    """Update the status of a suggestion (e.g., accepted, dismissed)."""
    if body.status not in {"open", "accepted", "dismissed", "done"}:
        raise HTTPException(400, "bad status")
    db.set_suggestion_status(sid, body.status)
    return {"ok": True}


@app.post("/api/review")
def review():
    """Manually trigger the deterministic proactive reviewer."""
    return {"new_suggestions": reviewer.run_review()}


@app.get("/api/digest")
def digest():
    """Weekly-digest style summary written by the LLM from stored memory."""
    rows = db.list_repos()
    sugg = db.list_suggestions(status="open")
    if not rows:
        return {"digest": "Nothing synced yet."}
    facts = "\n".join(f"- {r['name']}: last push {r['pushed_at'][:10]}, stats={r['stats']}" for r in rows)
    todo = "\n".join(f"- {s['repo']}: {s['title']}" for s in sugg[:30]) or "none"
    prompt = (
        "Write a short weekly engineering digest (max 200 words, Markdown) for a developer's personal projects. "
        "Say which repos are active, which are stale, and the 3 most valuable things to do next.\n\n"
        f"Repos:\n{facts}\n\nOpen suggestions:\n{todo}"
    )
    return {"digest": llm_text(get_llm(0.3).invoke(prompt))}


# Serve static frontend files
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/")
def index():
    """Serve the frontend index HTML."""
    return FileResponse(STATIC / "index.html")
