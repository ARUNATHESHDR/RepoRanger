"""The agent: a LangGraph state machine.

        START -> agent --(no tool calls)--> END
                   |
                   +--(read tools)--> tools --> agent
                   |
                   +--(write tool)--> approval --(approved)--> tools --> agent
                                          |
                                          +--(rejected)------> agent

Concepts: typed State, nodes, conditional edges, ToolNode, checkpointer (short-term memory),
interrupt() for human-in-the-loop approval.
"""
# Import the standard library 'sqlite3' to connect to the checkpointer database.
import sqlite3
# Import type hints from the standard library.
from typing import Annotated, Literal

# Import LangChain core message classes and utilities.
from langchain_core.messages import AIMessage, SystemMessage, ToolMessage, trim_messages
# Import the SQLite checkpointer from LangGraph for short-term conversation memory.
from langgraph.checkpoint.sqlite import SqliteSaver
# Import core LangGraph components for building the state machine.
from langgraph.graph import END, START, StateGraph
# Import a built-in reducer to append messages to the state array.
from langgraph.graph.message import add_messages
# Import the built-in ToolNode to execute LangChain tools.
from langgraph.prebuilt import ToolNode
# Import Command and interrupt to control graph execution and implement human-in-the-loop.
from langgraph.types import Command, interrupt
# Import TypedDict for typing the graph State.
from typing_extensions import TypedDict

# Import local modules for database access, configuration, LLM initialization, and tools.
from . import db
from .config import settings
from .llm import get_llm, llm_text
from .tools import ALL_TOOLS, WRITE_TOOL_NAMES

# Define the base system prompt instructions for the LLM.
SYSTEM = """You are a personal engineering assistant for the user's own GitHub projects.
You track their repos, discuss them, and suggest concrete improvements.

Rules:
- Ground every claim in tool results. For anything about a repo, call tools first (get_repo_overview, search_code, read_file...).
- When you point at code, cite the file path (and line numbers when you have read the file).
- Never invent repos, files or commits. If you do not know, say so and look it up.
- Respect earlier suggestions: do not re-suggest items marked dismissed.
- To create a GitHub issue use create_issue. The user is asked to approve it first, so just call it with a clear title and body.
- Be concise and practical. Prefer a short prioritised list over long essays.

Tracked repos right now:
{repos}
"""


# Define the State type for the graph, which holds a list of messages.
class State(TypedDict):
    # Annotated with add_messages so that returning new messages appends to the list instead of overwriting.
    messages: Annotated[list, add_messages]


# Define a helper function to dynamically generate the system prompt containing the current synced repos.
def _system_prompt() -> SystemMessage:
    # Fetch all synced repos from the database and format them as a comma-separated string.
    repos = ", ".join(r["name"] for r in db.list_repos()) or "(none synced yet)"
    # Inject the repo list into the SYSTEM prompt template and return it as a SystemMessage.
    return SystemMessage(SYSTEM.format(repos=repos))


# Define the function to build and compile the LangGraph state machine.
def build_graph():
    # Instantiate the LLM and bind the available tools to it.
    llm = get_llm().bind_tools(ALL_TOOLS)

    # Define the primary 'agent' node which invokes the LLM.
    def agent(state: State):
        # Trim the conversation history to the last 30 messages to prevent exceeding context limits, starting on a human message.
        history = trim_messages(
            state["messages"],
            strategy="last",
            token_counter=len,  # count messages, not tokens (simple + good enough here)
            max_tokens=30,
            start_on="human",
            allow_partial=False,
        )
        # Return a dictionary containing the new AIMessage generated by the LLM.
        return {"messages": [llm.invoke([_system_prompt(), *history])]}

    # Define the conditional router function to determine the next node based on the agent's output.
    def route(state: State) -> Literal["tools", "approval", "__end__"]:
        # Get the last message in the state.
        last = state["messages"][-1]
        # Extract any tool calls from the last message.
        calls = getattr(last, "tool_calls", None) or []
        # If there are no tool calls, the conversation turn ends.
        if not calls:
            return END
        # If any of the requested tool calls are in the restricted 'WRITE_TOOL_NAMES' list, route to the 'approval' node.
        if any(c["name"] in WRITE_TOOL_NAMES for c in calls):
            return "approval"
        # Otherwise, route directly to the 'tools' execution node.
        return "tools"

    # Define the 'approval' node for human-in-the-loop tool execution.
    def approval(state: State) -> Command[Literal["tools", "agent"]]:
        # Get the last message (which is the AIMessage requesting the write tool).
        last: AIMessage = state["messages"][-1]
        # Execution pauses here. The API returns the payload; resuming provides the decision.
        decision = interrupt(
            {
                "type": "approval_required",
                "actions": [{"id": c["id"], "tool": c["name"], "args": c["args"]} for c in last.tool_calls],
            }
        )
        # If the user approved the action when resuming, transition to the 'tools' node to execute it.
        if decision.get("approved"):
            return Command(goto="tools")
        # If the user rejected the action, create synthetic ToolMessages simulating a failed execution to tell the LLM it was rejected.
        rejections = [
            ToolMessage(content="The user rejected this action. Do not retry it; ask what they want instead.", tool_call_id=c["id"])
            for c in last.tool_calls
        ]
        # Return to the 'agent' node, appending the rejection messages to the state.
        return Command(goto="agent", update={"messages": rejections})

    # Initialize a new StateGraph using the State definition.
    g = StateGraph(State)
    # Add the 'agent' node to the graph.
    g.add_node("agent", agent)
    # Add a built-in ToolNode to handle tool execution.
    g.add_node("tools", ToolNode(ALL_TOOLS))
    # Add the custom 'approval' node.
    g.add_node("approval", approval)
    # Set the entry point of the graph to the 'agent' node.
    g.add_edge(START, "agent")
    # Add conditional edges branching from the 'agent' node using the 'route' function.
    g.add_conditional_edges("agent", route, {"tools": "tools", "approval": "approval", END: END})
    # Add a deterministic edge from the 'tools' node back to the 'agent' node.
    g.add_edge("tools", "agent")

    # Initialize the SQLite checkpointer to persist conversation threads, allowing state to resume across API calls.
    checkpointer = SqliteSaver(sqlite3.connect(settings.checkpoint_path, check_same_thread=False))
    # Compile and return the graph, attaching the checkpointer.
    return g.compile(checkpointer=checkpointer)


# Global variable to cache the compiled graph instance.
_graph = None


# Define a function to lazily initialize and retrieve the graph singleton.
def get_graph():
    global _graph
    # If the graph hasn't been built yet, build it.
    if _graph is None:
        _graph = build_graph()
    # Return the compiled graph instance.
    return _graph


# Define a helper function to inspect a thread's state and return the pending interrupt payload if it is paused.
def _pending(config: dict) -> dict | None:
    # Get the current state snapshot for the given thread configuration.
    snap = get_graph().get_state(config)
    # Iterate through pending tasks and their interrupts.
    for task in snap.tasks:
        for it in task.interrupts:
            # Return the value payload of the first found interrupt.
            return it.value
    # If there are no interrupts, return None.
    return None


# Define a helper function to format the graph's output for the API response.
def _result(config: dict, state: dict) -> dict:
    # Check if the graph is currently paused pending approval.
    pending = _pending(config)
    # If it is pending, return a placeholder reply and the pending payload for the UI to display.
    if pending:
        return {"reply": "I need your approval before doing this.", "pending": pending}
    # Otherwise, extract the final AIMessage content from the state.
    last = state["messages"][-1]
    text = llm_text(last)
    # Return the reply and None for pending.
    return {"reply": text, "pending": None}


# Define the main entry point for sending a chat message to the agent.
def chat(thread_id: str, message: str) -> dict:
    # Prepare the configuration dictionary specifying the thread ID and recursion limit.
    config = {"configurable": {"thread_id": thread_id}, "recursion_limit": 25}
    # Invoke the graph, passing in the user's message as a new message.
    state = get_graph().invoke({"messages": [("user", message)]}, config)
    # Process and return the result.
    return _result(config, state)


# Define the entry point for resuming the graph execution after human approval/rejection.
def resume(thread_id: str, approved: bool) -> dict:
    # Prepare the configuration dictionary for the correct thread.
    config = {"configurable": {"thread_id": thread_id}, "recursion_limit": 25}
    # Invoke the graph using a Command to resume execution with the user's decision.
    state = get_graph().invoke(Command(resume={"approved": approved}), config)
    # Process and return the result.
    return _result(config, state)
